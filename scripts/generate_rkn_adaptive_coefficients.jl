        println(io, "pub(crate) const $(prefix)_ORDER: usize = $(order);")
        println(io, "pub(crate) const $(prefix)_POS_ONLY_ERROR: bool = $(tableau.pos_only_error);\n")
    end
    for (prefix, constructor, order) in VELOCITY_DEPENDENT_METHODS
