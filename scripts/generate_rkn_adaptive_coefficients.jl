function rust_float(value::Float64)
    text = @sprintf("%.17g", value)
    if !occursin(r"[.eE]", text)
        text *= ".0"
    end
    replace(text, "e+" => "e")
end

function emit_array(io, name, values)
    println(io, "pub(crate) const $(name): &[f64] = &[")
    for value in values
        println(io, "    $(rust_float(value)),")
    end
    println(io, "];\n")
end

output = joinpath(@__DIR__, "..", "src", "rkn_adaptive_coefficients.rs")
open(output, "w") do io
    println(io, "// @generated by scripts/generate_rkn_adaptive_coefficients.jl")
    println(io, "// OrdinaryDiffEq.jl revision 211142263781255a9aa2f910f6760b9f18ec29c8.\n")
